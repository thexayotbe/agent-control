// Glue words between phrases: «короче», «бля», «сука»… Makes the lines sound spoken, not written.
const GLUE = ['бля', 'короче', 'сука', 'нахуй', 'типа', 'ёпта', 'в натуре', 'пиздец', 'слышь', 'походу', 'ну', 'блядь', 'хули', 'ебать']
const OPENERS = ['слышь,', 'короче,', 'бля,', 'ну', 'ёпта,', 'сука,', 'ебать,']

/** sprinkle Russian glue words and мат into a line (rude mode only) */
export function spice(text: string, rnd: () => number = Math.random): string {
  if (!CYR.test(text)) return text
  const pick = <T,>(a: T[]) => a[Math.floor(rnd() * a.length)]
  let t = text.replace(/([,—]) /g, (m, p) => (rnd() < 0.5 ? `${p} ${pick(GLUE)}, ` : m))
  const words = t.split(' ')
  if (words.length > 4 && rnd() < 0.4) {
    const i = 1 + Math.floor(rnd() * (words.length - 2))
    words.splice(i, 0, pick(GLUE))
    t = words.join(' ')
  }
  if (rnd() < 0.35 && !/^(слышь|короче|бля|ну|ёпта|сука|ебать)/i.test(t)) t = `${pick(OPENERS)} ${t}`
  if (rnd() < 0.25 && !/[?!]$/.test(t)) t = `${t}, ${pick(['блядь', 'нахуй', 'сука', 'пиздец'])}`
  return t
}
