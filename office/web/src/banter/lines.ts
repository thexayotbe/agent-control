function merge(a: LineSet, b: Partial<Record<ChatEvent, Pool>>): LineSet {
  const out = {} as LineSet
  for (const ev of Object.keys(a) as ChatEvent[]) {
    const pool: Pool = {}
    const keys = new Set([...Object.keys(a[ev]), ...Object.keys(b[ev] ?? {})]) as Set<Persona | 'any'>
    for (const k of keys) pool[k] = [...(a[ev][k] ?? []), ...(b[ev]?.[k] ?? [])]
    out[ev] = pool
  }
  return out
}

